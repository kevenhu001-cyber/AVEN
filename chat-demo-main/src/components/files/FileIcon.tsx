const PPT_EXTS = ['PPT', 'PPTX']

/** ext 为大写扩展名 */
export function FileIcon({ ext }: { ext: string }) {
  if (IMAGE_EXTS.includes(ext)) {
    return <ImageIcon />
  }
  if (ext === 'PDF') {
    return <PdfIcon />
  }
  if (TABLE_EXTS.includes(ext)) {
    return <TableFileIcon />
  }
  if (PPT_EXTS.includes(ext)) {
    return <PptFileIcon />
  }
  return <OtherFileIcon />
}

